CREATE TABLE mood_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date DATE NOT NULL,
    reader_id VARCHAR(36) NOT NULL,
    mood VARCHAR(20) NOT NULL CHECK(mood IN ('HAPPY','CALM','TIRED','LOW','HOPEFUL')),
    CONSTRAINT uq_daily_mood UNIQUE(entry_date,reader_id)
);
CREATE TABLE guest_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(40) NOT NULL,
    body VARCHAR(2000) NOT NULL,
    reply VARCHAR(2000),
    status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','HIDDEN')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_guest_public ON guest_messages(status,created_at DESC,id DESC);
CREATE TABLE reader_polls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question VARCHAR(160) NOT NULL,
    options VARCHAR(2000) NOT NULL,
    active_slot INTEGER UNIQUE CHECK(active_slot IS NULL OR active_slot = 1),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE poll_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id BIGINT NOT NULL REFERENCES reader_polls(id) ON DELETE CASCADE,
    reader_id VARCHAR(36) NOT NULL,
    option_index INTEGER NOT NULL CHECK(option_index BETWEEN 0 AND 5),
    CONSTRAINT uq_poll_vote UNIQUE(poll_id,reader_id)
);
