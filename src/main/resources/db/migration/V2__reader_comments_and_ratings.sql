CREATE TABLE reader_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    nickname VARCHAR(40) NOT NULL,
    body VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'HIDDEN')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_comments_public ON reader_comments(post_id, status, created_at DESC, id DESC);
CREATE INDEX idx_comments_moderation ON reader_comments(status, created_at DESC, id DESC);
CREATE TABLE reader_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    reader_id VARCHAR(36) NOT NULL,
    stars INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT uq_reader_rating UNIQUE (post_id, reader_id)
);
